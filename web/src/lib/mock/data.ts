// assetRef turns an asset id into an asset reference attached to a finding (label order matches the backend coverageNodeLabel
// order: URL > domain > IP > app name). The "by asset" view's tree relies on these references
// to attach findings to assets.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

